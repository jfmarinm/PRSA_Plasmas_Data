#!/usr/bin/env python3
"""Figure 5, independent exact Sagdeev/Gaussian-quadrature Python calculation.

No precomputed data files. Uses stable Bernoulli-minus-log(n) Taylor series and local quadrature
near the rarefactive double-layer turning root. All data and PDF/PNG files
are regenerated by `python fig5.py`.
"""
from __future__ import annotations
import argparse,csv
from dataclasses import dataclass,field
import numpy as np
from numpy.polynomial.legendre import leggauss
from numpy.polynomial.polynomial import polyval
from scipy.optimize import brentq
from scipy.integrate import solve_ivp
from scipy.interpolate import PchipInterpolator
import matplotlib.pyplot as plt
from figure_style import configure,style,letter,export,output_paths,BLUE,COPPER,PURPLE,SLATE,GREY,LIGHT

@dataclass
class Parameters:
    sigma:float=.2
    p1:float=1.
    p2:float=-6.
    Vref:float=.0012
    p3c:float=6.
    series_order:int=48
    def __post_init__(self):
        self.lam=np.sqrt(1+self.sigma*self.p1)
        assert abs(self.p2+self.lam**2/self.sigma)<1e-10
        self.xg,self.wg=self.gauss(40)
        self.xw,self.ww=self.gauss(160)
    @staticmethod
    def gauss(N):
        x,w=leggauss(N)
        return (x+1)/2,w/2


def pp(n,p3,q):
    y=np.asarray(n)-1
    return q.p1+2*q.p2*y+3*p3*y*y

def bp(n,p3,V,q):
    n=np.asarray(n)
    return ((q.lam+V)**2-q.sigma*n*n*pp(n,p3,q))/n**3

def bpp(n,p3,V,q):
    n=np.asarray(n); y=n-1; M=q.lam+V
    return -3*M*M/n**4-q.sigma*((2*q.p2+6*p3*y)/n-pp(n,p3,q)/n**2)

def hfun(y,p3,V,q):
    y=np.asarray(y)
    dM=V*(2*q.lam+V)
    k=np.arange(4,q.series_order+1)
    coeff=np.r_[dM,-1.5*dM,2*dM-q.sigma*(p3-q.p3c),
       (-1.)**(k-1)*(.5*(q.lam+V)**2*(k+1)-(1+q.sigma*(q.p1-2*q.p2+3*p3))/k)]
    return y*polyval(y,coeff)

def hder_p3(y,q):
    k=np.arange(3,q.series_order+1)
    coeff=np.zeros(q.series_order)
    coeff[k-1]=(-1.)**k*(3*q.sigma/k)
    return np.asarray(y)*polyval(y,coeff)

def p3_equilibrium(n,V,q):
    y=n-1
    return q.p3c-hfun(y,q.p3c,V,q)/hder_p3(y,q)

def S(n,p3,V,q):
    sh=np.shape(n)
    yy=np.asarray(n,dtype=float).reshape(-1)-1
    tt=yy[:,None]*q.xg[None,:]
    nn=1+tt
    f=-nn*np.expm1(hfun(tt,p3,V,q))*bp(nn,p3,V,q)
    return (yy*(f@q.wg)).reshape(sh)[()] if sh==() else (yy*(f@q.wg)).reshape(sh)

def Sfrom(n0,n,p3,V,q):
    sh=np.shape(n)
    dd=np.asarray(n,dtype=float).reshape(-1)-n0
    t=n0+dd[:,None]*q.xg[None,:]
    f=-t*np.expm1(hfun(t-1,p3,V,q))*bp(t,p3,V,q)
    vals=(dd*(f@q.wg)).reshape(sh)
    return vals[()] if sh==() else vals

def B(n,p3,V,q):
    n=np.asarray(n)
    return np.log(n)+hfun(n-1,p3,V,q)

def first_zero_pressure_slope(p3,q):
    return 1+2*q.p1/(-2*q.p2+np.sqrt((2*q.p2)**2-12*p3*q.p1))

def kappa_dl2(n,p3,V,q):
    y=n-1
    dM=V*(2*q.lam+V)
    numerator=dM-q.lam**2*y**3*(3*n+1)-3*q.sigma*(p3-q.p3c)*n*n*y*y
    denom=(q.lam+V)**2-q.sigma*n*n*pp(n,p3,q)
    return n*numerator/denom

def solve_dl(V,q):
    r=(V/q.Vref)**(1/3)
    lo,hi=1-.30*r,1-.12*r
    fn=lambda n:float(S(n,p3_equilibrium(n,V,q),V,q)/(n-1)**5)
    n=brentq(fn,lo,hi,xtol=1e-14)
    p3=float(p3_equilibrium(n,V,q))
    if not (0<n<1 and p3>q.p3c):
        raise ValueError('Inadmissible double-layer endpoint')
    return n,p3

def turn_density(p3,n_dl,V,q):
    if p3<=p3_equilibrium(n_dl,V,q):raise ValueError('p3 below DL threshold')
    root=brentq(lambda n:float(S(n,p3,V,q)),n_dl,.999,xtol=1e-14)
    assert n_dl<root<1 and bp(root,p3,V,q)>0
    return root

def profile(nt,p3,V,q):
    def f(_z,u):
        n,nd=u
        return [nd,(n*np.expm1(hfun(n-1,p3,V,q))-bpp(n,p3,V,q)*nd**2)/bp(n,p3,V,q)]
    def event(_t,u):return u[0]-.99995
    event.direction=1
    event.terminal=True
    sol=solve_ivp(f,(0,240),[nt,0],rtol=1e-10,atol=2e-12,
                  max_step=.5,events=event)
    if not sol.success: raise RuntimeError(sol.message)
    z=np.linspace(0,180,550)
    ni=np.ones_like(z)
    mask=z<=sol.t[-1]
    ni[mask]=PchipInterpolator(sol.t,sol.y[0])(z[mask])
    phi=B(ni,p3,V,q)
    return np.r_[-z[1:][::-1],z],np.r_[phi[1:][::-1],phi]

def width80(nt,p3,V,q):
    amplitude=float(B(nt,p3,V,q))
    nth=brentq(lambda n:float(B(n,p3,V,q)-.8*amplitude),nt,.9999,xtol=1e-14)
    dn=nth-nt
    t=q.xw
    n=nt+dn*t*t
    ds=Sfrom(nt,n,p3,V,q)
    if np.any(ds>=0):raise ValueError('Nonnegative S in width integral')
    integrand=2*dn*t*bp(n,p3,V,q)/np.sqrt(-2*ds)
    return 2*np.dot(q.ww,integrand)

def calculate(q):
    n_ref,p_ref=solve_dl(q.Vref,q)
    ell_ref=1/np.sqrt(kappa_dl2(n_ref,p_ref,q.Vref,q))
    # Panel (a): compressive orbit pressure threshold and rarefactive DL locus.
    p_min=brentq(lambda p:float(S(first_zero_pressure_slope(p,q),p,0,q)),5.4,5.8)
    p_press=np.linspace(p_min+2e-5,9,130)
    v_press=np.array([brentq(lambda v:float(S(first_zero_pressure_slope(p,q),p,v,q)),0,.025,xtol=1e-14) for p in p_press])
    v_map=np.geomspace(1e-8,.002,60)
    p_map=np.array([solve_dl(v,q)[1] for v in v_map])
    prof_p=np.array([8.,7.9,7.8945])
    profiles=[profile(turn_density(p,n_ref,q.Vref,q),p,q.Vref,q) for p in prof_p]
    dw=np.array([.1,.03,.01,.003,.001,.0003,.0001,.00003,.00001,.000003,.000001,.0000003,.0000001,.00000001])
    widths=np.array([width80(turn_density(p_ref+d,n_ref,q.Vref,q),p_ref+d,q.Vref,q) for d in dw])
    x_width=np.log(1/dw)
    asym=widths[-1]+ell_ref*(x_width-x_width[-1])
    v_len=np.array([1e-12,1e-11,1e-10,1e-9,1e-8,1e-7,1e-6,1e-5,1e-4,q.Vref])
    n_len,p_len=zip(*(solve_dl(v,q) for v in v_len))
    n_len=np.array(n_len);p_len=np.array(p_len)
    dlen=p_len-q.p3c
    dm=v_len*(2*q.lam+v_len)
    ell0=1/np.sqrt(dm/(1+dm))
    ell_dl=1/np.sqrt(kappa_dl2(n_len,p_len,v_len,q))
    C=np.sqrt(216)*q.lam**2/(5*q.sigma**1.5)
    print(f'p3_DL(Vref) = {p_ref:.15f}; kappa_DL^-1 = {ell_ref:.8f}')
    print(f'W80 last secant slope = {(widths[-1]-widths[-2])/(x_width[-1]-x_width[-2]):.8f}')
    return locals()

def write_csv(base,T):
    def out(name,header,cols):
        with open(str(base)+name+'.csv','w',newline='') as f:
            w=csv.writer(f);w.writerow(header);w.writerows(zip(*cols))
    out('_admissibility',['p3','V_threshold'],[T['p_press'],T['v_press']])
    out('_dl_map',['V','p3_DL'],[T['v_map'],T['p_map']])
    out('_flat_top_widths',['delta_p3','W80'],[T['dw'],T['widths']])
    out('_localization',['V','delta_p3','ell0','ell_DL'],[T['v_len'],T['dlen'],T['ell0'],T['ell_dl']])


    ax.set(xlim=(5.5,9),ylim=(0,1.78),xlabel=r'$p_3$',ylabel=r'$10^3V$')
    ax.set_xticks(np.arange(5.5,9.1,.5)); ax.set_yticks(np.arange(0,1.61,.4));style(ax,12,grid=True)
    letter(ax,'a',(.025,1.11));ax.legend(loc='upper left',bbox_to_anchor=(.065,.98),fontsize=9)
    ax=fig.add_axes(pos[1]);
    for (z,f),p,color,ls in zip(T['profiles'],T['prof_p'],[BLUE,COPPER,PURPLE],['-','--','-']):
        ax.plot(z,f,ls,color=color,lw=1.8,label=rf'$p_3={p:.5g}$')
    ax.set(xlim=(-175,175),ylim=(-.23,.02),xlabel=r'$\zeta$',ylabel=r'$\phi(\zeta)$')
    ax.set_xticks(np.arange(-150,151,50)); ax.set_yticks([-.2,-.15,-.1,-.05,0]);style(ax,12,grid=True)
    letter(ax,'b',(.025,1.11));ax.legend(loc='lower right',fontsize=9)
    ax=fig.add_axes(pos[2]);
    ax.plot(T['x_width'],T['widths'],'-o',color=COPPER,lw=1.8,ms=4.2,label='Exact quadrature')
    ax.plot(T['x_width'],T['asym'],'--',color=BLUE,lw=1.8,label=r'Slope $1/\kappa_{\mathrm{DL}}$')
    ax.set(xlim=(1.9,19.4),ylim=(20,220),xlabel=r'$\ln[1/(p_3-p_{3,\mathrm{DL}})]$',ylabel=r'$W_{80}$')
    ax.set_xticks(np.arange(2,19,2));ax.set_yticks(np.arange(20,221,40));style(ax,11,grid=True)
    letter(ax,'c',(.025,1.11));ax.legend(loc='upper left',bbox_to_anchor=(.065,.83),fontsize=9)
    ax=fig.add_axes(pos[3]);

    ax=fig.add_axes(pos[0]); ax.plot(T['p_press'],1e3*T['v_press'],lw=1.8,color=BLUE,label='Compressive')
    ax.plot(T['p_map'],1e3*T['v_map'],lw=1.8,color=COPPER,label='Rarefactive')
    ax.axvline(6,color=LIGHT,ls=':',lw=.85)
    ax.axhline(1e3*q.Vref,color=GREY,ls='--',lw=1)
